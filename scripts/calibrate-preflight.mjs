/**
 * Derive the pre-flight's BM25 support thresholds from the committed corpora.
 *
 * The factory's groundability stage uses embedding cosine with cut-offs of
 * 0.68 / 0.78. Those numbers were derived against bge-small and mean nothing
 * for BM25, so the hosted pre-flight needs its own, derived the same way:
 * score things already known to be covered, score things already known to be
 * absent, and look for a gap.
 *
 * Labels come from artifacts, not from judgement:
 *   POSITIVE  a run's must_answer topics, probed against that run's own corpus
 *             (the committed 02_groundability.json adjudicated these as
 *             supported or weak -- never unsupported)
 *   NEGATIVE  a run's must_refuse topics, probed against its own corpus, plus
 *             every run's must_answer topics probed against the OTHER run's
 *             corpus, which is as clean a negative as the repository holds:
 *             a real topic, real phrasing, documents that cannot cover it
 *
 * Run: node scripts/calibrate-preflight.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { bm25, tokenize } from "../lib/bm25.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "data", "runs");
const RUNS = ["hr_policy_live", "ship_spares_live"];

const load = (p) => JSON.parse(readFileSync(p, "utf8"));

/** Same scoring the pre-flight uses: raw BM25 of the best chunk, per term. */
function score(clause, chunks) {
  const raw = bm25(clause, chunks, 1, 1.5, 0.75, false);
  const terms = Math.max(tokenize(clause).length, 1);
  return raw.length > 0 ? raw[0].score / terms : 0;
}

const corpora = {};
const topics = {};
for (const id of RUNS) {
  corpora[id] = load(join(root, id, "web", "chunks.json")).chunks;
  const req = load(join(root, id, "01_requirements.json"));
  topics[id] = {
    answer: req.must_answer.map((t) => `${t.name}. ${t.description}`),
    refuse: req.must_refuse.map((t) => `${t.name}. ${t.description}`),
  };
}

const positives = [];
const negatives = [];

for (const id of RUNS) {
  for (const t of topics[id].answer) {
    positives.push({ label: `${id} <- own must_answer`, t, s: score(t, corpora[id]) });
  }
  for (const t of topics[id].refuse) {
    negatives.push({ label: `${id} <- own must_refuse`, t, s: score(t, corpora[id]) });
  }
  for (const other of RUNS) {
    if (other === id) continue;
    for (const t of topics[id].answer) {
      negatives.push({ label: `${other} <- ${id} must_answer`, t, s: score(t, corpora[other]) });
    }
  }
}

const stat = (xs) => {
  const v = xs.map((x) => x.s).sort((a, b) => a - b);
  const mid = Math.floor(v.length / 2);
  return {
    n: v.length,
    min: v[0],
    max: v[v.length - 1],
    median: v.length % 2 ? v[mid] : (v[mid - 1] + v[mid]) / 2,
  };
};

const P = stat(positives);
const N = stat(negatives);
const f = (x) => Number(x.toFixed(4));

console.log("\n=== covered clauses (positives) ===");
for (const p of positives.sort((a, b) => a.s - b.s)) {
  console.log(`  ${f(p.s).toFixed(4)}  ${p.label}  ${p.t.slice(0, 58)}`);
}
console.log("\n=== absent clauses (negatives) ===");
for (const n of negatives.sort((a, b) => b.s - a.s)) {
  console.log(`  ${f(n.s).toFixed(4)}  ${n.label}  ${n.t.slice(0, 58)}`);
}

const overlap = positives.filter((p) => p.s <= N.max).length;
const separates = N.max < P.min;

console.log("\n=== separation ===");
console.log(`  positives n=${P.n}  min ${f(P.min)}  median ${f(P.median)}  max ${f(P.max)}`);
console.log(`  negatives n=${N.n}  min ${f(N.min)}  median ${f(N.median)}  max ${f(N.max)}`);

if (separates) {
  console.log(`  CLEAN SEPARATION. any cut-off in (${f(N.max)}, ${f(P.min)}) splits them.`);
  console.log(`  TAU_UNSUPPORTED = ${((N.max + P.min) / 2).toFixed(2)}, TAU_SUPPORTED = ${P.median.toFixed(2)}`);
} else {
  console.log(`  OVERLAP: ${overlap} of ${P.n} positives score at or below the top negative (${f(N.max)}).`);
  console.log(`  No cut-off separates these sets, so the pre-flight ships WITHOUT a`);
  console.log(`  supported/unsupported verdict. It shows the passage and the score and`);
  console.log(`  lets the reader judge. A badge here would be decoration.`);
  console.log(`  Cause: a must-refuse topic is written in the documents' own vocabulary`);
  console.log(`  ("must not recommend a supplier" against a supplier agreement), so`);
  console.log(`  lexical overlap is high exactly where support is absent.`);
}

const out = {
  _README:
    "Generated by scripts/calibrate-preflight.mjs. Decides whether the hosted " +
    "pre-flight may show a supported/unsupported verdict. It may only do so if " +
    "separates is true. Labels are taken from committed run artifacts, not judged.",
  generated_from: RUNS,
  positives: { ...P, min: f(P.min), max: f(P.max), median: f(P.median) },
  negatives: { ...N, min: f(N.min), max: f(N.max), median: f(N.median) },
  separates,
  overlapping_positives: overlap,
  verdict: separates
    ? "separable - thresholds may be used"
    : "not separable - pre-flight must not classify",
};
writeFileSync(join(here, "..", "data", "preflight-calibration.json"), JSON.stringify(out, null, 2) + "\n");
console.log("\n  wrote data/preflight-calibration.json\n");
